"""
Hidden-mass control of a mass-spring-damper system
==================================================
GRU imitation policy versus fixed, oracle (true-mass) and RLS-scheduled LQI
controllers under a temporally aligned, paired, multi-seed evaluation protocol.

This is the reference implementation of the accompanying paper.  Equation
numbers quoted in the comments, e.g. ``Eq. (12)``, refer to that paper.

Protocol
--------
* Plant ``m(t) x'' + b x' + k_s x = u`` with k_s = 2, b = 0.5 and an unmeasured,
  piecewise-constant mass m(t).
* Expert demonstrations: 144 trajectories of 10 s generated by the true-mass
  LQI on noisy measurements (forward Euler, T_c = 0.02 s, seed 42); split
  100 / 21 / 23 at trajectory level before sequence construction.
* Evaluation: plant integrated at T_p = 0.01 s; measurements, integral state,
  RLS adaptation, GRU history buffer and commands updated at T_c = 0.02 s with
  zero-order hold.  One canonical and 59 randomized scenarios (seed 2026);
  scenario i uses the noise seed 42000 + 10000 i for every controller.
* GRU policy: history L = 30, one GRU layer (72 units), LayerNorm-96-48-1 head,
  SiLU, dropout 0.03, Smooth-L1 loss, AdamW, five optimization seeds.
* Secondary studies: conditional-clamping anti-windup (data regenerated and
  policies retrained), history length L in {15, 30, 45}, one-factor-at-a-time
  RLS sensitivity, canonical-scenario composition check.
* Statistics: seed-averaged paired Wilcoxon tests with Holm correction, paired
  t-tests, per-seed repeatability, exact McNemar tests on settling.

Outputs
-------
``csv_outputs/``, ``models/`` and every figure in three formats
(``figures_pdf_vector/``, ``figures_svg_vector/``, ``figures_png_600dpi/``),
plus an editable diagrams.net file of the workflow diagram.

Usage
-----
    python hidden_mass_gru_benchmark.py                          # full study
    python hidden_mass_gru_benchmark.py --models-from models/    # reuse trained policies
    python hidden_mass_gru_benchmark.py --figures-from results/  # figures only
    python hidden_mass_gru_benchmark.py --architecture-only      # workflow diagram only

From Jupyter:  ``from hidden_mass_gru_benchmark import main; main(out="results")``
"""

