# 4. Expert demonstrations and trajectory-wise partition (Section 2.2)
# =============================================================================

def generate_teacher_trajectory(rng: np.random.Generator, gains: GainTable, mode: str,
                                cfg: Config = CFG) -> Tuple[np.ndarray, np.ndarray]:
    n = int(round(cfg.t_train / cfg.dt_control))                           # 500 Eq. (6)
    r = sample_reference(rng, cfg)
    switches, masses = sample_mass_schedule(rng, cfg.t_train, cfg, window=cfg.train_switch_window)
    sc = Scenario(-1, r, 0.0, 0.0, switches, masses, "teacher")
    x = np.array([rng.uniform(-cfg.train_x0_range, cfg.train_x0_range),
                  rng.uniform(-cfg.train_v0_range, cfg.train_v0_range)], dtype=float)
    z, u_prev, v_prev = 0.0, 0.0, None
    X = np.zeros((n, cfg.input_dim), dtype=np.float32)
    y = np.zeros((n, 1), dtype=np.float32)
    for k in range(n):
        t = k * cfg.dt_control
        m = mass_at(t, sc)
        xm = x[0] + rng.normal(0.0, cfg.sigma_x)
        vm = x[1] + rng.normal(0.0, cfg.sigma_v)
        acc = 0.0 if v_prev is None else (vm - v_prev) / cfg.dt_control   # Eq. (20)
        v_prev = vm
        Kx, Ki = gains.gains(m)
        u_raw = -float(Kx @ np.array([xm, vm])) - Ki * z                   # Eq. (35)
        u = sat(u_raw, cfg)
        X[k] = build_feature(xm, vm, r, z, u_prev, acc)
        y[k, 0] = u
        e = r - xm
        a = (u - cfg.b_damping * x[1] - cfg.k_spring * x[0]) / m          # forward Euler, 0.02 s
        x = np.array([x[0] + x[1] * cfg.dt_control, x[1] + a * cfg.dt_control])
        dz, _ = integral_increment(e, u_raw, mode, cfg)
        z += dz
        u_prev = u
    return X, y


@dataclass
class DemoDataset:
    mode: str
    trajectories: List[Tuple[np.ndarray, np.ndarray]]
    train_ids: np.ndarray
    val_ids: np.ndarray
    test_ids: np.ndarray
    x_mean: np.ndarray
    x_std: np.ndarray
    y_mean: np.ndarray
    y_std: np.ndarray


def build_demo_dataset(mode: str, gains: GainTable, cfg: Config = CFG) -> DemoDataset:
    rng = np.random.default_rng(cfg.data_seed)
    trajs = [generate_teacher_trajectory(rng, gains, mode, cfg) for _ in range(cfg.num_teacher_trajectories)]
    perm = rng.permutation(cfg.num_teacher_trajectories)
    tr = perm[: cfg.n_train_traj]
    va = perm[cfg.n_train_traj: cfg.n_train_traj + cfg.n_val_traj]
    te = perm[cfg.n_train_traj + cfg.n_val_traj:]
    Xtr = np.concatenate([trajs[i][0] for i in tr]); ytr = np.concatenate([trajs[i][1] for i in tr])
    xm, xs = Xtr.mean(0).astype(np.float32), Xtr.std(0).astype(np.float32)
    ym, ys = ytr.mean(0).astype(np.float32), ytr.std(0).astype(np.float32)
    xs = np.where(xs < 1e-8, 1.0, xs).astype(np.float32)               # Eq. (23)
    ys = np.where(ys < 1e-8, 1.0, ys).astype(np.float32)               # Eq. (24)
    return DemoDataset(mode, trajs, tr, va, te, xm, xs, ym, ys)


def make_sequences(ds: DemoDataset, ids: Sequence[int], L: int) -> TensorDataset:
    """Left-padded sliding windows: one sequence per controller sample Eq. (11)."""
    seqs, ys = [], []
    for i in ids:
        X, y = ds.trajectories[int(i)]
        Xn = ((X - ds.x_mean) / ds.x_std).astype(np.float32)
        yn = ((y - ds.y_mean) / ds.y_std).astype(np.float32)
        pad = np.vstack([np.repeat(Xn[:1], L - 1, axis=0), Xn])
        idx = np.arange(Xn.shape[0])[:, None] + np.arange(L)[None, :]
        seqs.append(pad[idx]); ys.append(yn)
    return TensorDataset(torch.from_numpy(np.concatenate(seqs)), torch.from_numpy(np.concatenate(ys)))


