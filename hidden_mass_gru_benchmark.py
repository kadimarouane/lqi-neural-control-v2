@dataclass
class Scenario:
    scenario_id: int
    reference: float
    initial_position: float
    initial_velocity: float
    switch_times: List[float]
    masses: List[float]
    scenario_type: str = "randomized"


def sample_reference(rng: np.random.Generator, cfg: Config = CFG) -> float:
    """Uniform on [-2.5, 3.0] with projection to |r| >= 0.8 Eq. (7)."""
    r = float(rng.uniform(cfg.reference_low, cfg.reference_high))
    if abs(r) < cfg.reference_min_abs:
        r = math.copysign(cfg.reference_min_abs, r if r != 0 else 1.0)
    return r


def sample_mass_schedule(rng: np.random.Generator, t_end: float, cfg: Config = CFG,
                         window: Optional[Tuple[float, float]] = None) -> Tuple[List[float], List[float]]:
    """Piecewise-constant hidden mass with 2-5 segments, >= 0.8 s separation and
    |m_{q+1} - m_q| >= 0.4 Eq. (10)."""
    n_seg = int(rng.integers(cfg.min_segments, cfg.max_segments + 1))
    if window is None:
        lower = max(cfg.min_switch_separation, cfg.eval_switch_fraction[0] * t_end)
        upper = cfg.eval_switch_fraction[1] * t_end
    else:
        lower, upper = window
    candidates = np.sort(rng.uniform(lower, upper, size=n_seg - 1)).tolist()
    switches: List[float] = []
    for s in candidates:
        if not switches or abs(s - switches[-1]) >= cfg.min_switch_separation:
            switches.append(float(s))
    n_seg = len(switches) + 1
    grid = gain_grid(cfg)
    allowed = np.asarray([m for m in grid if cfg.random_mass_low <= m <= cfg.random_mass_high])
    masses = rng.choice(allowed, size=n_seg, replace=True).astype(float)
    for i in range(1, n_seg):
        if abs(masses[i] - masses[i - 1]) < cfg.min_adjacent_mass_gap:
            pool = allowed[np.abs(allowed - masses[i - 1]) >= cfg.resample_adjacent_mass_gap]
            masses[i] = float(rng.choice(pool))
    return switches, masses.tolist()


def mass_at(t: float, sc: Scenario) -> float:
    seg = 0
    for s in sc.switch_times:
        if t >= s:
            seg += 1
        else:
            break
    return float(sc.masses[min(seg, len(sc.masses) - 1)])


def make_eval_scenarios(cfg: Config = CFG) -> List[Scenario]:
    """Canonical scenario Eq. (13) + 59 randomized scenarios (seed 2026)."""
    rng = np.random.default_rng(cfg.evaluation_scenario_seed)
    out = [Scenario(0, 2.0, 0.0, 0.0, [2.0, 14.0], [1.0, 6.0, 4.0], "canonical")]
    for sid in range(1, cfg.num_randomized_scenarios + 1):
        r = sample_reference(rng, cfg)
        x0 = float(rng.uniform(-cfg.eval_x0_range, cfg.eval_x0_range))
        v0 = float(rng.uniform(-cfg.eval_v0_range, cfg.eval_v0_range))
        sw, ms = sample_mass_schedule(rng, cfg.t_test, cfg)
        out.append(Scenario(sid, r, x0, v0, sw, ms, "randomized"))
    return out


def scenario_noise(sid: int, n_updates: int, cfg: Config = CFG) -> Tuple[np.ndarray, np.ndarray]:
    """Scenario-specific noise stream, drawn (position, velocity) per controller
    update with seed 42000 + 10000 i Eq. (74)."""
    rng = np.random.default_rng(cfg.noise_seed_base + cfg.noise_seed_stride * sid)
    nx = np.empty(n_updates); nv = np.empty(n_updates)
    for k in range(n_updates):
        nx[k] = rng.normal(0.0, cfg.sigma_x)
        nv[k] = rng.normal(0.0, cfg.sigma_v)
    return nx, nv


def build_feature(xm: float, vm: float, r: float, z: float, u_prev: float, acc: float) -> np.ndarray:
    """Seven-dimensional observation xi_k Eq. (22)."""
    return np.array([xm, vm, r, z, u_prev, r - xm, acc], dtype=np.float32)


