def gain_grid(cfg: Config = CFG) -> np.ndarray:
    """96-point grid {0.5, 0.6, ..., 10.0} Eq. (32)."""
    return np.round(np.linspace(cfg.mass_min, cfg.mass_max, 96), 8)


def design_lqi(mass: float, cfg: Config = CFG) -> Tuple[np.ndarray, float]:
    """Continuous-time LQI gain K_a(m) = [K_x(m) K_i(m)] Eqs. (30), (31)."""
    A = np.array([[0.0, 1.0], [-cfg.k_spring / mass, -cfg.b_damping / mass]])
    B = np.array([[0.0], [1.0 / mass]])
    Aa = np.zeros((3, 3)); Aa[:2, :2] = A; Aa[2, 0] = -1.0
    Ba = np.zeros((3, 1)); Ba[:2, 0] = B[:, 0]
    Q = np.diag([cfg.q_pos, cfg.q_vel, cfg.q_int])
    R = np.array([[cfg.r_control]])
    S = solve_continuous_are(Aa, Ba, Q, R)
    K = np.linalg.solve(R, Ba.T @ S)
    return K[0, :2].astype(float), float(K[0, 2])


class GainTable:
    def __init__(self, cfg: Config = CFG):
        self.grid = gain_grid(cfg)
        gains = [design_lqi(float(m), cfg) for m in self.grid]
        self.Kx = np.array([g[0] for g in gains])
        self.Ki = np.array([g[1] for g in gains])

    def index(self, mass: float) -> int:
        """Nearest-neighbour lookup Eq. (34)."""
        return int(np.argmin(np.abs(self.grid - mass)))

    def gains(self, mass: float) -> Tuple[np.ndarray, float]:
        i = self.index(mass)
        return self.Kx[i], float(self.Ki[i])

    def to_frame(self) -> pd.DataFrame:
        return pd.DataFrame({"mass_kg": self.grid, "K_p": self.Kx[:, 0], "K_v": self.Kx[:, 1], "K_i": self.Ki})


def sat(u: float, cfg: Config = CFG) -> float:
    """sat_[-u_max, u_max] Eq. (36); non-finite commands map to 0."""
    if not np.isfinite(u):
        return 0.0
    return float(min(cfg.u_max, max(-cfg.u_max, u)))


def integral_increment(z_err: float, u_raw: float, mode: str, cfg: Config = CFG) -> Tuple[float, int]:
    """Common integral update Eq. (16) or conditional clamping
    Eq. (17).  Returns (increment, hold_flag)."""
    if mode == "conditional_clamping":
        if (u_raw > cfg.u_max and z_err > 0.0) or (u_raw < -cfg.u_max and z_err < 0.0):
            return 0.0, 1
    return cfg.dt_control * z_err, 0


