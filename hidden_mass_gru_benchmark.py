@dataclass
class RLSParams:
    lam: float = CFG.rls_lambda
    window: int = CFG.rls_window
    rate_limit: float = CFG.rls_rate_limit


class RLSMassEstimator:
    def __init__(self, p: RLSParams, cfg: Config = CFG):
        self.p, self.cfg = p, cfg
        self.m_hat = cfg.rls_initial_mass                     # Eq. (53)
        self.theta = 1.0 / self.m_hat
        self.P = cfg.rls_p0
        self.a_bar = 0.0
        self.prev: Optional[Tuple[float, float]] = None
        self.window: deque = deque(maxlen=p.window)
        self.n_acc = 0

    def update(self, xm: float, vm: float, u_prev: float) -> Tuple[float, float, float, int]:
        """Returns (m_hat, residual, phi, accepted)."""
        c = self.cfg
        if self.prev is None:                                  # first call stores state only
            self.prev = (xm, vm)
            return self.m_hat, float("nan"), float("nan"), 0
        x_prev, v_prev = self.prev
        a_raw = (vm - v_prev) / c.dt_control                                    # Eq. (39)
        self.a_bar = c.rls_alpha * a_raw + (1 - c.rls_alpha) * self.a_bar        # Eq. (40)
        phi = u_prev - c.b_damping * v_prev - c.k_spring * x_prev               # Eq. (41)
        resid, acc = float("nan"), 0
        if abs(phi) >= c.rls_phi_min and abs(self.a_bar) >= c.rls_a_min:        # Eq. (43)
            den = self.p.lam + phi * self.P * phi
            if np.isfinite(den) and den > 1e-12:
                g = self.P * phi / den                                          # Eq. (45)
                resid = self.a_bar - phi * self.theta                           # Eq. (46)
                th = self.theta + g * resid                                     # Eq. (47)
                if np.isfinite(th):
                    self.theta = float(np.clip(th, 1 / c.mass_max, 1 / c.mass_min))   # Eq. (49)
                    self.P = float(np.clip((self.P - g * phi * self.P) / self.p.lam, c.rls_p_min, c.rls_p_max))
                    self.window.append(1.0 / self.theta)                        # Eq. (54)
                    self.n_acc += 1; acc = 1
        if len(self.window) > 0:
            target = float(np.median(np.asarray(self.window)))                   # Eq. (55)
            dm = float(np.clip(target - self.m_hat, -self.p.rate_limit, self.p.rate_limit))
            self.m_hat = float(np.clip(self.m_hat + dm, c.mass_min, c.mass_max))  # Eq. (56)
        self.prev = (xm, vm)
        return self.m_hat, resid, phi, acc


