def settling_time(t: np.ndarray, e: np.ndarray, tol: float) -> float:
    """Eq. (86); +inf (here NaN) when the band is not held to the end."""
    out = np.where(np.abs(e) > tol)[0]
    if len(out) == 0:
        return 0.0
    j = int(out[-1])
    return float("nan") if j >= len(t) - 1 else float(t[j + 1])


def switch_events(t: np.ndarray, err: np.ndarray, sc: Scenario, tol: float, horizon: float) -> List[Dict[str, float]]:
    """Per-switch recovery Eq. (89) with follow-up H_q ."""
    ev = []
    for q, tau in enumerate(sc.switch_times):
        nxt = sc.switch_times[q + 1] if q + 1 < len(sc.switch_times) else horizon
        seg = np.where((t >= tau) & (t < nxt))[0]
        if len(seg) == 0:
            continue
        bad = np.where(np.abs(err[seg]) > tol)[0]
        if len(bad) == 0:
            rec = float(t[seg[0]] - tau)
        elif bad[-1] >= len(seg) - 1:
            rec = float("nan")
        else:
            rec = float(t[seg[bad[-1] + 1]] - tau)
        H = float(nxt - tau)
        ev.append({"switch_index": q, "switch_time_s": tau, "next_switch_or_horizon_s": nxt,
                   "available_followup_s": H, "recovery_success": int(np.isfinite(rec)),
                   "recovery_time_s": rec, "recovery_time_penalized_s": rec if np.isfinite(rec) else H})
    return ev


def estimator_events(t: np.ndarray, m_hat: np.ndarray, sc: Scenario, horizon: float, cfg: Config = CFG) -> List[Dict[str, float]]:
    """Eq. (93)."""
    ev = []
    for q, tau in enumerate(sc.switch_times):
        nxt = sc.switch_times[q + 1] if q + 1 < len(sc.switch_times) else horizon
        seg = np.where((t >= tau) & (t < nxt))[0]
        if len(seg) == 0:
            continue
        m_new = float(sc.masses[q + 1])
        tol = max(cfg.estimator_recovery_ratio * abs(m_new), cfg.estimator_recovery_floor)
        dev = np.abs(m_hat[seg] - m_new)
        bad = np.where(dev > tol)[0]
        if len(bad) == 0:
            rec = float(t[seg[0]] - tau)
        elif bad[-1] >= len(seg) - 1:
            rec = float("nan")
        else:
            rec = float(t[seg[bad[-1] + 1]] - tau)
        H = float(nxt - tau)
        ev.append({"switch_index": q, "switch_time_s": tau, "target_mass_kg": m_new, "tolerance_kg": tol,
                   "estimator_recovery_success": int(np.isfinite(rec)), "estimator_recovery_time_s": rec,
                   "estimator_recovery_time_penalized_s": rec if np.isfinite(rec) else H,
                   "post_switch_peak_mass_error_kg": float(np.max(dev))})
    return ev


def closed_loop_metrics(lg: Dict[str, np.ndarray], sc: Scenario, cfg: Config = CFG) -> Tuple[Dict[str, float], List[Dict], List[Dict]]:
    t, x, u = lg["t"], lg["position"], lg["u"]
    dt = cfg.dt_plant
    horizon = float(t[-1] + dt)
    e = sc.reference - x                                                         # Eq. (76)
    tol = cfg.settling_band_ratio * max(abs(sc.reference), 1e-9)
    A_r = max(abs(sc.reference - x[0]), 1e-9)                                    # Eq. (82)
    os_ = max(0.0, float(np.max((x - sc.reference) * np.sign(sc.reference)))) / A_r * 100.0   # Eq. (83)
    ts = settling_time(t, e, tol)
    ev = switch_events(t, e, sc, tol, horizon)
    uc = lg["u_commands"]; du = np.diff(uc); ddu = np.diff(du)
    rec = np.array([q["recovery_time_s"] for q in ev], float)
    pen = np.array([q["recovery_time_penalized_s"] for q in ev], float)
    fin = rec[np.isfinite(rec)]
    met = {
        "RMSE_track": float(np.sqrt(np.mean(e ** 2))),                         # Eq. (77)
        "MAE_track": float(np.mean(np.abs(e))),
        "IAE": float(dt * np.sum(np.abs(e))),                                  # Eq. (78)
        "ISE": float(dt * np.sum(e ** 2)),
        "ITAE": float(dt * np.sum(t * np.abs(e))),                             # Eq. (79)
        "Overshoot_percent": float(os_),
        "Settling_time_2pct_s": ts,
        "Settled_2pct_success": float(np.isfinite(ts)),
        "Settling_failure": float(not np.isfinite(ts)),
        "Settling_time_2pct_penalized_s": ts if np.isfinite(ts) else horizon,  # Eq. (87)
        "Recovery_mean_after_switch_s": float(np.mean(fin)) if len(fin) else float("nan"),
        "Recovery_max_after_switch_s": float(np.max(fin)) if len(fin) else float("nan"),
        "Recovery_success_count": float(len(fin)),
        "Recovery_switch_count": float(len(ev)),
        "Recovery_failure_count": float(len(ev) - len(fin)),
        "Recovery_success_rate": float(len(fin) / len(ev)) if ev else float("nan"),
        "Recovery_penalized_mean_after_switch_s": float(np.mean(pen)) if ev else float("nan"),  # Eq. (90)
        "Final_abs_error": float(abs(e[-1])),
        "Control_energy": float(dt * np.sum(u ** 2)),                          # Eq. (80)
        "Control_RMS": float(np.sqrt(np.mean(u ** 2))),
        "Max_abs_u": float(np.max(np.abs(u))),
        "Saturation_fraction": float(np.mean(np.abs(uc) >= 0.999 * cfg.u_max)),
        "Total_variation_u": float(np.sum(np.abs(du))),                        # Eq. (81)
        "Mean_abs_du": float(np.mean(np.abs(du))),
        "Mean_abs_ddu": float(np.mean(np.abs(ddu))),
        "Controller_update_count": float(len(uc)),
        "Anti_windup_hold_fraction": float(lg["hold_fraction"][0]),
    }
    est_ev: List[Dict] = []
    mh = lg["mass_hat"]
    if "rls_update_fraction" in lg:
        dm = mh - lg["mass_true"]
        est_ev = estimator_events(t, mh, sc, horizon, cfg)
        met.update({
            "Mass_hat_MAE": float(np.mean(np.abs(dm))),                         # Eq. (92)
            "Mass_hat_RMSE": float(np.sqrt(np.mean(dm ** 2))),
            "Mass_hat_bias": float(np.mean(dm)),
            "Mass_hat_final_abs_error": float(abs(dm[-1])),
            "Mass_estimator_update_fraction": float(lg["rls_update_fraction"][0]),
            "Mass_estimator_mean_abs_residual": float(lg["rls_mean_abs_residual"][0]),
            "Mass_estimator_mean_abs_regressor": float(lg["rls_mean_abs_regressor"][0]),
            "Mass_estimator_recovery_success_rate": float(np.mean([q["estimator_recovery_success"] for q in est_ev])) if est_ev else np.nan,
            "Mass_estimator_recovery_mean_s": float(np.nanmean([q["estimator_recovery_time_s"] for q in est_ev])) if any(q["estimator_recovery_success"] for q in est_ev) else np.nan,
            "Mass_estimator_recovery_penalized_mean_s": float(np.mean([q["estimator_recovery_time_penalized_s"] for q in est_ev])) if est_ev else np.nan,
            "Mass_estimator_postswitch_peak_error_mean_kg": float(np.mean([q["post_switch_peak_mass_error_kg"] for q in est_ev])) if est_ev else np.nan,
        })
    return met, ev, est_ev


