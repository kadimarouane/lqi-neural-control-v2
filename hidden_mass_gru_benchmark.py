def evaluate_mode(mode: str, scenarios: List[Scenario], gains: GainTable, policies: Dict[int, LoadedPolicy],
                  cfg: Config = CFG, rls_params: Optional[RLSParams] = None, keep_logs: Sequence[int] = (0,)
                  ) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, Dict]:
    rows, ev_rows, est_rows, kept = [], [], [], {}
    for ctrl in CLASSICAL:
        for sc in scenarios:
            lg = simulate_classical(ctrl, sc, gains, mode, rls_params, cfg)
            met, ev, est = closed_loop_metrics(lg, sc, cfg)
            base = {"anti_windup_mode": mode, **scenario_row(sc), "training_seed": np.nan, "Controller": ctrl}
            rows.append({**base, **met})
            ev_rows += [{**{k: base[k] for k in ("anti_windup_mode", "scenario_type", "scenario_id", "training_seed", "Controller")}, **q} for q in ev]
            est_rows += [{**{k: base[k] for k in ("anti_windup_mode", "scenario_type", "scenario_id", "Controller")}, **q} for q in est]
            if sc.scenario_id in keep_logs:
                kept[(ctrl, None, sc.scenario_id)] = lg
        print(f"  [{mode}] {SHORT[ctrl]} evaluated", flush=True)
    for seed, pol in policies.items():
        logs = simulate_gru_batch(pol, scenarios, mode, cfg)
        for sc, lg in zip(scenarios, logs):
            met, ev, _ = closed_loop_metrics(lg, sc, cfg)
            base = {"anti_windup_mode": mode, **scenario_row(sc), "training_seed": seed, "Controller": CTRL_GRU}
            rows.append({**base, **met})
            ev_rows += [{**{k: base[k] for k in ("anti_windup_mode", "scenario_type", "scenario_id", "training_seed", "Controller")}, **q} for q in ev]
            if sc.scenario_id in keep_logs:
                kept[(CTRL_GRU, seed, sc.scenario_id)] = lg
        print(f"  [{mode}] GRU seed {seed} evaluated", flush=True)
    return pd.DataFrame(rows), pd.DataFrame(ev_rows), pd.DataFrame(est_rows), kept


