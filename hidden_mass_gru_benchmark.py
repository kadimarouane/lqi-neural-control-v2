def get_policies(mode: str, L: int, seeds: Sequence[int], gains: GainTable, paths: Paths, models_from: Optional[Path],
                 cfg: Config, offline_rows: List, hist_rows: List, ds_cache: Dict) -> Dict[int, LoadedPolicy]:
    pols: Dict[int, LoadedPolicy] = {}
    for seed in seeds:
        name = f"gru_aw-{mode}_L{L}_seed{seed}.pt"
        target = paths.models / name
        src = models_from / name if models_from is not None else None
        if not target.exists() and src is not None and src.exists():
            shutil.copy2(src, target)
        if not target.exists():
            if mode not in ds_cache:
                print(f"  generating expert demonstrations ({mode})", flush=True)
                ds_cache[mode] = build_demo_dataset(mode, gains, cfg)
            ds = ds_cache[mode]
            model, hist = train_policy(ds, seed, L, cfg)
            save_checkpoint(target, model, ds, mode, seed, L, cfg)
            hist.insert(0, "training_seed", seed); hist.insert(0, "seq_len", L); hist.insert(0, "anti_windup_mode", mode)
            hist_rows.append(hist)
            offline_rows.append({"anti_windup_mode": mode, "seq_len": L, "training_seed": seed, **offline_metrics(model, ds, L, cfg)})
        pols[seed] = load_checkpoint(target, L, cfg)
    return pols


