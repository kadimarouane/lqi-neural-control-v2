def _robust_save(fig: plt.Figure, target: Path, **kw) -> Path:
    """Save via a temporary file then atomic replace; retry when Windows keeps the
    target locked (image viewer, OneDrive/antivirus scan).  If it stays locked the
    figure is written next to it with a timestamp suffix instead of crashing."""
    import time as _t
    tmp = target.with_name(target.stem + ".tmp" + target.suffix)
    fig.savefig(tmp, **kw)
    for attempt in range(6):
        try:
            os.replace(tmp, target)
            return target
        except OSError:
            _t.sleep(0.5 * (attempt + 1))
    alt = target.with_name(f"{target.stem}_{_t.strftime('%H%M%S')}{target.suffix}")
    os.replace(tmp, alt)
    print(f"  WARNING: {target.name} is locked (open in another program?) -> saved as {alt.name}", flush=True)
    return alt


def save_figure(fig: plt.Figure, stem: str, paths: Paths, cfg: Config = CFG) -> None:
    _robust_save(fig, paths.pdf / f"{stem}.pdf")
    _robust_save(fig, paths.svg / f"{stem}.svg")
    _robust_save(fig, paths.png / f"{stem}.png", dpi=cfg.figure_dpi)
    plt.close(fig)
    print(f"  figure saved: {stem} (.pdf/.svg/.png)", flush=True)


