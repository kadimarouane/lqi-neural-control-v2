def _markup(s: str, target: str) -> str:
    import re
    if target == "html":
        s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        s = re.sub(r"_\{([^}]*)\}", r"<sub>\1</sub>", s)
        s = re.sub(r"\^\{([^}]*)\}", r"<sup>\1</sup>", s)
        return s.replace("\n", "<br>")
    s = re.sub(r"_\{([^}]*)\}", lambda m: "$_{\\mathrm{" + m.group(1).replace(" ", "\\ ") + "}}$", s)
    s = re.sub(r"\^\{([^}]*)\}", lambda m: "$^{\\mathrm{" + m.group(1).replace(" ", "\\ ") + "}}$", s)
    return s


