def _arch_fonts() -> Tuple[List[str], Dict[str, object]]:
    """Return (family list, body-text font kwargs).  Titles use bold (700); body
    text uses a real medium/semibold face when installed, never a fake bold:
    Windows -> 'Segoe UI Semibold' file; Linux/macOS -> Fira Sans / Inter 500."""
    import logging
    from matplotlib import font_manager
    logging.getLogger("matplotlib.font_manager").setLevel(logging.ERROR)
    weights: Dict[str, set] = {}
    for f in font_manager.fontManager.ttflist:
        w = f.weight if isinstance(f.weight, int) else {"normal": 400, "regular": 400, "medium": 500, "semibold": 600,
                                                        "demibold": 600, "bold": 700}.get(str(f.weight).lower(), 400)
        weights.setdefault(f.name, set()).add(int(w))
    for fam in ("Segoe UI", "Fira Sans", "Inter Display", "Arial", "DejaVu Sans"):
        if fam not in weights:
            continue
        for semi in (fam + " Semibold", fam + " SemiBold", fam + " Medium"):
            if semi in weights:
                return [fam, "DejaVu Sans"], {"fontfamily": [semi, fam], "fontweight": "normal"}
        w = weights[fam]
        body_w = 500 if 500 in w else 600 if 600 in w else "normal"
        return [fam, "DejaVu Sans"], {"fontweight": body_w}
    return ["DejaVu Sans"], {"fontweight": "normal"}


