def between_seed_summary(df: pd.DataFrame, metrics: Sequence[str] = PRIMARY_METRICS) -> pd.DataFrame:
    """Eq. (98) with Student-t (4 dof) intervals."""
    g = df[df["Controller"] == CTRL_GRU].groupby("training_seed")[list(metrics) + ["Settled_2pct_success", "Recovery_success_count", "Recovery_switch_count"]].agg(
        {**{m: "mean" for m in metrics}, "Settled_2pct_success": "mean", "Recovery_success_count": "sum", "Recovery_switch_count": "sum"})
    rows = []
    n = len(g)
    for m in metrics:
        v = g[m].to_numpy(); mu, sd = v.mean(), v.std(ddof=1)
        h = stats.t.ppf(0.975, n - 1) * sd / np.sqrt(n)
        rows.append({"metric": m, "mean_of_seed_means": mu, "between_seed_sd": sd, "t95_low": mu - h, "t95_high": mu + h,
                     "seed_mean_min": v.min(), "seed_mean_max": v.max()})
    out = pd.DataFrame(rows)
    succ = g["Settled_2pct_success"] * 100; rec = g["Recovery_success_count"] / g["Recovery_switch_count"] * 100
    extra = pd.DataFrame([{"metric": "Settling_success_percent", "seed_mean_min": succ.min(), "seed_mean_max": succ.max(), "mean_of_seed_means": succ.mean()},
                          {"metric": "Pooled_recovery_percent", "seed_mean_min": rec.min(), "seed_mean_max": rec.max(), "mean_of_seed_means": rec.mean()}])
    return pd.concat([out, extra], ignore_index=True)


def mcnemar_by_seed(df: pd.DataFrame) -> pd.DataFrame:
    rls = df[df["Controller"] == CTRL_RLS].set_index("scenario_id")["Settled_2pct_success"]
    rows = []
    for seed, g in df[df["Controller"] == CTRL_GRU].groupby("training_seed"):
        gs = g.set_index("scenario_id")["Settled_2pct_success"].reindex(rls.index)
        n_g = int(((gs == 1) & (rls == 0)).sum()); n_r = int(((gs == 0) & (rls == 1)).sum())
        nd = n_g + n_r                                                                # Eq. (99)
        p = float(stats.binomtest(n_g, nd, 0.5).pvalue) if nd > 0 else 1.0
        rows.append({"training_seed": int(seed), "endpoint": "scenario_settling", "n_GRU_only": n_g,
                     "n_RLS_only": n_r, "n_discordant": nd, "exact_mcnemar_p": p,
                     "GRU_successes": int(gs.sum()), "RLS_successes": int(rls.sum()), "n_scenarios": int(len(rls))})
    out = pd.DataFrame(rows)
    out["exact_mcnemar_p_holm_within_seed_2endpoints"] = np.minimum(1.0, 2.0 * out["exact_mcnemar_p"])
    return out


def success_counts(df: pd.DataFrame) -> pd.DataFrame:
    """Explicit success/failure counts (settling per scenario, pooled switch recovery)."""
    rows = []
    for (ctrl, seed), g in df.groupby(["Controller", df["training_seed"].fillna(-1)]):
        sd = np.nan if seed == -1 else float(seed)
        n, k = len(g), int(g["Settled_2pct_success"].sum())
        rows.append({"outcome": "settling", "Controller": ctrl, "training_seed": sd, "n_opportunities": n,
                     "n_success": k, "n_failure": n - k, "success_rate": k / n})
        n, k = int(g["Recovery_switch_count"].sum()), int(g["Recovery_success_count"].sum())
        rows.append({"outcome": "switch_recovery_pooled", "Controller": ctrl, "training_seed": sd, "n_opportunities": n,
                     "n_success": k, "n_failure": n - k, "success_rate": k / n if n else np.nan})
    return pd.DataFrame(rows).sort_values(["outcome", "Controller", "training_seed"]).reset_index(drop=True)


