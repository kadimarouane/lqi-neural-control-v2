def _empty_log(n: int) -> Dict[str, np.ndarray]:
    keys = ("t", "position", "velocity", "mass_true", "mass_hat", "u")
    return {k: np.full(n, np.nan) for k in keys}


def simulate_classical(ctrl: str, sc: Scenario, gains: GainTable, mode: str,
                       rls_params: Optional[RLSParams] = None, cfg: Config = CFG) -> Dict[str, np.ndarray]:
    stride = int(round(cfg.dt_control / cfg.dt_plant))
    n_p = int(round(cfg.t_test / cfg.dt_plant)); n_c = n_p // stride
    nx, nv = scenario_noise(sc.scenario_id, n_c, cfg)
    x = np.array([sc.initial_position, sc.initial_velocity])
    z, u, u_prev = 0.0, 0.0, 0.0
    est = RLSMassEstimator(rls_params or RLSParams(), cfg) if ctrl == CTRL_RLS else None
    Kfix = gains.gains(cfg.nominal_fixed_mass)
    log = _empty_log(n_p)
    uc, holds, resids, phis = np.zeros(n_c), 0, [], []
    m_hat = float("nan")
    for j in range(n_p):
        t = j * cfg.dt_plant
        m = mass_at(t, sc)
        if j % stride == 0:
            k = j // stride
            xm, vm = x[0] + nx[k], x[1] + nv[k]
            e = sc.reference - xm                                              # Eq. (15)
            if ctrl == CTRL_FIXED:
                Kx, Ki = Kfix
            elif ctrl == CTRL_ORACLE:
                Kx, Ki = gains.gains(m); m_hat = m          # held between updates
            else:
                m_hat, r_, ph_, _ = est.update(xm, vm, u_prev)
                resids.append(r_); phis.append(ph_)
                Kx, Ki = gains.gains(m_hat)
            u_raw = -float(Kx @ np.array([xm, vm])) - Ki * z
            u = sat(u_raw, cfg)
            dz, h = integral_increment(e, u_raw, mode, cfg)
            z += dz; holds += h; uc[k] = u; u_prev = u
        log["t"][j], log["position"][j], log["velocity"][j] = t, x[0], x[1]
        log["mass_true"][j], log["mass_hat"][j], log["u"][j] = m, m_hat, u
        a = (u - cfg.b_damping * x[1] - cfg.k_spring * x[0]) / m
        x = np.array([x[0] + x[1] * cfg.dt_plant, x[1] + a * cfg.dt_plant])
    log["u_commands"] = uc
    log["hold_fraction"] = np.array([holds / n_c])
    if est is not None:
        log["rls_update_fraction"] = np.array([est.n_acc / n_c])
        r = np.asarray(resids, float); p = np.asarray(phis, float)
        log["rls_mean_abs_residual"] = np.array([np.nanmean(np.abs(r)) if np.any(np.isfinite(r)) else np.nan])
        log["rls_mean_abs_regressor"] = np.array([np.nanmean(np.abs(p)) if np.any(np.isfinite(p)) else np.nan])
    return log


def simulate_gru_batch(pol: LoadedPolicy, scenarios: Sequence[Scenario], mode: str,
                       cfg: Config = CFG) -> List[Dict[str, np.ndarray]]:
    """All scenarios advanced in lockstep; each keeps its own state, buffer,
    integral and noise stream.  Buffer prefilled with xi_init Eq. (60)."""
    S, L = len(scenarios), pol.seq_len
    stride = int(round(cfg.dt_control / cfg.dt_plant))
    n_p = int(round(cfg.t_test / cfg.dt_plant)); n_c = n_p // stride
    noise = [scenario_noise(sc.scenario_id, n_c, cfg) for sc in scenarios]
    r = np.array([sc.reference for sc in scenarios])
    x = np.array([sc.initial_position for sc in scenarios]); v = np.array([sc.initial_velocity for sc in scenarios])
    init = np.stack([build_feature(x[i], v[i], r[i], 0.0, 0.0, 0.0) for i in range(S)])
    buf = np.repeat(init[:, None, :], L, axis=1).astype(np.float32)
    z = np.zeros(S); u = np.zeros(S); u_prev = np.zeros(S); v_prev = np.full(S, np.nan)
    holds = np.zeros(S); uc = np.zeros((S, n_c))
    logs = [_empty_log(n_p) for _ in range(S)]
    for j in range(n_p):
        t = j * cfg.dt_plant
        m = np.array([mass_at(t, sc) for sc in scenarios])
        if j % stride == 0:
            k = j // stride
            xm = x + np.array([nz[0][k] for nz in noise]); vm = v + np.array([nz[1][k] for nz in noise])
            acc = np.where(np.isnan(v_prev), 0.0, (vm - v_prev) / cfg.dt_control)
            v_prev = vm
            feat = np.stack([xm, vm, r, z, u_prev, r - xm, acc], axis=1).astype(np.float32)
            buf = np.concatenate([buf[:, 1:, :], feat[:, None, :]], axis=1)
            inp = torch.from_numpy(((buf - pol.x_mean) / pol.x_std).astype(np.float32)).to(DEVICE)
            with torch.no_grad():
                un = pol.model(inp).cpu().numpy().reshape(-1)
            u_raw = pol.y_mean + pol.y_std * un.astype(np.float64)                # Eq. (65)
            u = np.array([sat(float(q), cfg) for q in u_raw])                     # Eq. (66)
            e = r - xm
            for i in range(S):
                dz, h = integral_increment(float(e[i]), float(u_raw[i]), mode, cfg)
                z[i] += dz; holds[i] += h
            uc[:, k] = u; u_prev = u.copy()
        for i in range(S):
            lg = logs[i]
            lg["t"][j], lg["position"][j], lg["velocity"][j] = t, x[i], v[i]
            lg["mass_true"][j], lg["u"][j] = m[i], u[i]
        a = (u - cfg.b_damping * v - cfg.k_spring * x) / m
        x, v = x + v * cfg.dt_plant, v + a * cfg.dt_plant
    for i in range(S):
        logs[i]["u_commands"] = uc[i]
        logs[i]["hold_fraction"] = np.array([holds[i] / n_c])
    return logs


